from models.questions import Question, Option

BIG_FIVE_NAMES = {'E':'外向性','A':'宜人性','C':'尽责性','S':'情绪稳定性','O':'智性与想象开放性'}
# 保留各维度官方 10 题及正反向键，呈现时交错维度。
RAW = {
'E': [('我是聚会中活跃气氛的人。',1),('与他人相处时，我感到自在。',1),('我会主动开启交谈。',1),('在聚会中，我会与许多不同的人交谈。',1),('我不介意成为大家关注的中心。',1),('我的话不多。',-1),('我通常待在不显眼的位置。',-1),('我常觉得没有太多话要说。',-1),('我不喜欢引起别人对我的注意。',-1),('在陌生人面前，我比较安静。',-1)],
'A': [('我对他人感兴趣。',1),('我能体谅别人的感受。',1),('我的心肠柔软。',1),('我愿意为别人抽出时间。',1),('我能感受到他人的情绪。',1),('我能让别人感到放松自在。',1),('我对他人并不怎么感兴趣。',-1),('我会用言语侮辱别人。',-1),('我对别人的难题不感兴趣。',-1),('我很少关心别人。',-1)],
'C': [('我总会做好准备。',1),('我注意细节。',1),('我会马上完成日常杂务。',1),('我喜欢井然有序。',1),('我按照日程安排做事。',1),('我对自己的工作要求严格。',1),('我常把自己的东西随处乱放。',-1),('我会把东西弄得杂乱。',-1),('我常忘记把东西放回原来的位置。',-1),('我会逃避自己的职责。',-1)],
'S': [('大多数时候，我感到放松。',1),('我很少感到情绪低落。',1),('我容易感到压力。',-1),('我会担心各种事情。',-1),('我容易受到困扰。',-1),('我容易心烦。',-1),('我的心情经常变化。',-1),('我的情绪经常起伏。',-1),('我容易被惹恼。',-1),('我经常感到情绪低落。',-1)],
'O': [('我的词汇量丰富。',1),('我的想象生动丰富。',1),('我有很好的点子。',1),('我能很快理解事物。',1),('我会使用较难的词语。',1),('我会花时间思考和反省。',1),('我的脑中充满想法。',1),('我难以理解抽象的想法。',-1),('我对抽象的想法不感兴趣。',-1),('我的想象力不太丰富。',-1)]}
ACCURACY = ['很不符合','较不符合','不确定／中间状态','较符合','很符合']

def build():
    questions=[]
    for row in range(10):
        for dim, items in RAW.items():
            text, polarity=items[row]
            questions.append(Question(len(questions)+1,dim,text,[Option(chr(65+i),label,dim,dim,score=i+1 if polarity==1 else 5-i) for i,label in enumerate(ACCURACY)]))
    return questions

BIG_FIVE_QUESTIONS=build()

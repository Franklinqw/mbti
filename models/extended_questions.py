FULL_QUESTIONS = list(QUESTIONS)
for dimension, rows in EXTRA.items():
    left, right = DIMENSION_LETTERS[dimension]
    for text, a, b in rows:
        index = len(FULL_QUESTIONS) + 1
        # 交替选项顺序，避免固定选择 A 总落在同一侧。
        choices = [(a, left), (b, right)]
        if index % 2 == 0:
            choices.reverse()
        FULL_QUESTIONS.append(Question(index, dimension, text, [
            Option(chr(65 + i), label, dimension, side)
            for i, (label, side) in enumerate(choices)
        ]))
